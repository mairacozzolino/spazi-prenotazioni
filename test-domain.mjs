import assert from 'node:assert/strict';
import {createInitialState,isFree,validateRequest,seatId,overlaps,calendarText,romeInstant} from './dist/domain.js';
const state=createInitialState('2026-10-13');
const date='2026-10-14';
const request={date,start:'12:30',end:'13:00'};
assert.equal(overlaps({date,start:'10:00',end:'11:00'},{date,start:'11:00',end:'12:00'}),false);
assert.equal(validateRequest(state,'meeting-1',request,'2026-10-13'),null);
state.bookings.push({id:'test',resource:seatId(1,1),...request,status:'confirmed'});
assert.equal(isFree(state,seatId(1,1),request),false);
assert.equal(isFree(state,seatId(1,2),request),true);
assert.match(validateRequest(state,'meeting-1',request,'2026-10-13'),/già una prenotazione/);
state.bookings[0].status='cancelled';
assert.equal(isFree(state,seatId(1,1),request),true);
assert.match(validateRequest(state,seatId(1,1),{...request,start:'11:00',end:'11:30'},'2026-10-13'),/pranzo/);
assert.match(validateRequest(state,'meeting-1',{...request,end:'15:00'},'2026-10-13'),/durata massima/);
assert.match(validateRequest(state,'meeting-1',{...request,end:'12:00'},'2026-10-13'),/successivo/);
assert.match(validateRequest(state,'meeting-1',{...request,date:'2026-10-12'},'2026-10-13'),/futuro/);
assert.match(validateRequest(state,'meeting-1',{...request,date:'2026-11-20'},'2026-10-13'),/30 giorni/);
assert.equal(romeInstant('2026-10-13','12:30').toISOString(),'2026-10-13T10:30:00.000Z');
assert.equal(romeInstant('2026-11-13','12:30').toISOString(),'2026-11-13T11:30:00.000Z');
const ics=calendarText({...request,id:'a',resource:seatId(1,1),title:'Test, riunione; team'},state.settings);
assert.match(ics,/DTSTART:20261014T103000Z/);
assert.match(ics,/SUMMARY:Test\\, riunione\\; team/);
console.log('13 verifiche superate: intervalli, disponibilità per posto, cancellazioni, regole, fuso di Roma e iCalendar.');

for(const date of [null,{},['2026-10-14']])assert.match(validateRequest(state,'meeting-1',{...request,date},'2026-10-13'),/data valida/);
for(const start of [null,{},['12:30']])assert.match(validateRequest(state,'meeting-1',{...request,start},'2026-10-13'),/orari validi/);
const unsafeCalendar=calendarText({...request,id:'safe',resource:'meeting-1',title:'Team\rATTENDEE:injected\r\nEND:VEVENT'},state.settings);
assert.equal(unsafeCalendar.split('\r\n').filter(line=>line==='END:VEVENT').length,1);
assert.equal(unsafeCalendar.split('\r\n').some(line=>line.startsWith('ATTENDEE:')),false);
